import { RefreshCw, Sparkles } from 'lucide-react'
import { Button, Card, ErrorState, LoadingState } from '../../components/ui'
import { SourceTag } from '../../components/comp'
import { generateSalaryAnalysis } from '../../services/ai'
import { useEvaluation } from '../../state/EvaluationContext'
import { useAI } from '../../state/useAI'

export function useNarrative() {
  const { aiContext } = useEvaluation()
  return useAI('narrative', aiContext, generateSalaryAnalysis)
}

export function AINarrativeCard() {
  const { result, loading, error, regenerate } = useNarrative()
  return (
    <Card className="p-5 sm:p-6">
      <div className="flex items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <Sparkles className="h-4 w-4 text-pine-600" aria-hidden />
          <h2 className="text-[15px] font-semibold text-ink-900">What this means for you</h2>
        </div>
        <div className="flex items-center gap-2">
          <SourceTag kind="ai" />
          {result && (
            <Button size="sm" variant="ghost" onClick={regenerate} aria-label="Regenerate interpretation" icon={<RefreshCw className="h-3.5 w-3.5" />} />
          )}
        </div>
      </div>
      <div className="mt-4">
        {loading && <LoadingState label="Interpreting your results…" lines={4} />}
        {error && <ErrorState message={error} onRetry={regenerate} />}
        {result && (
          <div className="animate-fadeUp">
            <p className="text-[15px] leading-relaxed text-ink-800">{result.data.summary}</p>
            <ul className="mt-4 space-y-2">
              {result.data.keyTakeaways.map((t) => (
                <li key={t} className="flex gap-2.5 text-sm leading-relaxed text-ink-700">
                  <span className="mt-2 h-1 w-1 shrink-0 rounded-full bg-pine-600" aria-hidden />
                  {t}
                </li>
              ))}
            </ul>
            <div className="mt-5 rounded-xl bg-ink-50 px-4 py-3">
              <p className="text-xs font-semibold text-ink-600">Keep in mind</p>
              <ul className="mt-1.5 space-y-1">
                {result.data.caveats.map((c) => <li key={c} className="text-xs leading-relaxed text-ink-500">· {c}</li>)}
              </ul>
            </div>
            {result.source !== 'llm' && (
              <p className="mt-3 text-[11px] text-ink-400">Generated by the local mock AI provider{result.source === 'fallback' ? ' (LLM unavailable)' : ''}.</p>
            )}
          </div>
        )}
      </div>
    </Card>
  )
}
